"""
Ground-truth validation of every kinetic method.

Synthetic datasets with a *known* activation energy are generated by
``isokinetics.validation`` -- independently of ``isokinetics.kinetics``
(its own gas constant, its own quadrature) -- and each method must
recover the known Ea within the tolerance justified by its theory.
"""

from __future__ import annotations

import numpy as np
import pytest

from isokinetics import kinetics, validation

BETAS = [5.0, 10.0, 20.0, 40.0]
WINDOW = (0.10, 0.90)


def _mean_ea(result):
    vals = [e for a, e in result.items() if WINDOW[0] <= a <= WINDOW[1] and np.isfinite(e)]
    return float(np.mean(vals))


# --------------------------------------------------------------------------- #
# Constant Ea: several models, low / medium / high Ea
# --------------------------------------------------------------------------- #
CASES = [
    ("F1", 150.0, 1e12), ("F2", 100.0, 1e8), ("R3", 250.0, 1e20),
    ("A2", 120.0, 1e10), ("D3", 80.0, 1e8),
]
#: relative tolerance (%): FWO carries the Doyle-approximation bias
TOL = {"Friedman": 0.5, "KAS": 1.0, "Starink": 0.5, "Vyazovkin": 0.5, "KTH": 0.5, "FWO": 5.0}


@pytest.fixture(scope="module", params=CASES, ids=lambda c: f"{c[0]}-{c[1]:g}")
def dataset(request):
    model, ea, a_pre = request.param
    return validation.simulate_constant_ea(ea, a_pre, model), ea


@pytest.mark.parametrize("method", list(TOL))
def test_method_recovers_known_ea(dataset, method):
    df, ea_true = dataset
    found = _mean_ea(kinetics.METHODS[method](df, BETAS))
    err = abs(found / ea_true - 1.0) * 100.0
    assert err <= TOL[method], f"{method}: {found:.3f} vs {ea_true} kJ/mol ({err:.2f} %)"


def test_ea_is_constant_across_alpha_for_constant_ea_data(dataset):
    """Friedman/Vyazovkin/KTH must be flat (not just right on average)."""
    df, ea_true = dataset
    for name in ("Friedman", "Vyazovkin", "KTH"):
        res = kinetics.METHODS[name](df, BETAS)
        vals = np.array([e for a, e in res.items() if 0.1 <= a <= 0.9])
        assert np.max(np.abs(vals / ea_true - 1.0)) < 0.01, name


# --------------------------------------------------------------------------- #
# Unit consistency
# --------------------------------------------------------------------------- #
def test_results_are_in_kj_per_mol_not_j_per_mol():
    df = validation.simulate_constant_ea(150.0, 1e12, "F1")
    for name, func in kinetics.METHODS.items():
        assert 100.0 < _mean_ea(func(df, BETAS)) < 200.0, name


def test_heating_rates_are_interpreted_in_k_per_min():
    """Scaling every beta by a common factor must not change Ea (only the
    intercept moves) -- and wrongly treating beta as K/s would not either,
    so also check A: it must come out in s^-1 (true value 1e12)."""
    df = validation.simulate_constant_ea(150.0, 1e12, "F1",
                                         alphas=np.round(np.arange(0.05, 0.95, 0.01), 2))
    cr = kinetics.coats_redfern(df, BETAS)
    a_found = cr["results"]["F1"]["A"]
    assert a_found == pytest.approx(1e12, rel=0.10)


def test_gas_constant_is_codata():
    assert kinetics.R == pytest.approx(8.314462618, rel=1e-9)


# --------------------------------------------------------------------------- #
# Regressions for the bugs found in the original Vyazovkin implementation
# --------------------------------------------------------------------------- #
def test_vyazovkin_correct_for_near_ambient_temperatures():
    """The old fixed 300 K lower integration limit returned ~115 kJ/mol
    for a true 45 kJ/mol when the reaction occurred around 260-400 K."""
    df = validation.simulate_constant_ea(45.0, 1e5, "F1")
    assert df[["T1", "T2", "T3", "T4"]].values.min() < 330.0
    res = kinetics.vyazovkin(df, BETAS)
    assert _mean_ea(res) == pytest.approx(45.0, rel=0.005)


def test_vyazovkin_not_clipped_at_500_kj_per_mol():
    df = validation.simulate_constant_ea(600.0, 1e50, "F1")
    assert _mean_ea(kinetics.vyazovkin(df, BETAS)) == pytest.approx(600.0, rel=0.005)


def test_vyazovkin_returns_nan_not_edge_value_without_interior_minimum():
    """Identical temperatures for every heating rate carry no kinetic
    information; the result must be NaN, not a bracket edge."""
    import pandas as pd
    df = pd.DataFrame({"alpha": [0.1, 0.2, 0.3], "T1": [500., 510., 520.],
                       "T2": [500., 510., 520.], "T3": [500., 510., 520.],
                       "T4": [500., 510., 520.]})
    res = kinetics.vyazovkin(df, BETAS)
    assert all(np.isnan(v) or v not in (30.0, 500.0) for v in res.values())


def test_classic_vyazovkin_still_available():
    df = validation.simulate_constant_ea(150.0, 1e12, "F1")
    res = kinetics.vyazovkin(df, BETAS, advanced=False)
    assert _mean_ea(res) == pytest.approx(150.0, rel=0.005)


def test_temperature_integral_matches_closed_form():
    """int_x^inf e^-u/u^2 du = e^-x/x - E1(x); E1 via a convergent series."""
    from math import exp, log
    def e1(x):  # series for x <= 5, continued fraction otherwise
        if x <= 5:
            s, term = -0.5772156649015329 - log(x), 1.0
            for k in range(1, 80):
                term *= -x / k
                s -= term / k
            return s
        f = 0.0
        for k in range(60, 0, -1):
            f = k / (1.0 + k / (x + f))
        return exp(-x) / (x + f)
    xs = np.array([3.0, 5.0, 10.0, 25.0, 60.0])
    exact = np.array([exp(-x) / x - e1(x) for x in xs])
    assert np.allclose(kinetics._temperature_integral_p(xs), exact, rtol=1e-7)


# --------------------------------------------------------------------------- #
# Variable Ea(alpha)
# --------------------------------------------------------------------------- #
@pytest.fixture(scope="module")
def variable_dataset():
    ea = lambda a: 100.0 + 100.0 * a  # noqa: E731
    return validation.simulate_variable_ea(ea, 1e10, "F1"), ea


@pytest.mark.parametrize("method,tol_pct", [
    ("Friedman", 0.5), ("Vyazovkin", 1.5), ("KTH", 1.5),
    ("FWO", 5.0), ("KAS", 5.0), ("Starink", 5.0),
])
def test_variable_ea_tracked(variable_dataset, method, tol_pct):
    df, ea = variable_dataset
    res = kinetics.METHODS[method](df, BETAS)
    pts = [(a, e) for a, e in res.items() if 0.1 <= a <= 0.9]
    mae = np.mean([abs(e - ea(a)) for a, e in pts]) / np.mean([ea(a) for a, _ in pts]) * 100
    assert mae <= tol_pct, f"{method}: MAE {mae:.2f} %"


def test_windowed_vyazovkin_beats_whole_range_form_when_ea_varies(variable_dataset):
    df, ea = variable_dataset
    def mae(res):
        return np.mean([abs(e - ea(a)) for a, e in res.items() if 0.1 <= a <= 0.9])
    adv = mae(kinetics.vyazovkin(df, BETAS))
    classic = mae(kinetics.vyazovkin(df, BETAS, advanced=False))
    assert adv < classic / 3


# --------------------------------------------------------------------------- #
# Coats-Redfern
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize("model,ea,a_pre", [("F1", 150.0, 1e12), ("R3", 150.0, 1e12), ("D3", 200.0, 1e15)])
def test_coats_redfern_recovers_ea_a_and_model(model, ea, a_pre):
    df = validation.simulate_constant_ea(ea, a_pre, model,
                                         alphas=np.round(np.arange(0.05, 0.95, 0.01), 2))
    cr = kinetics.coats_redfern(df, BETAS)
    fit = cr["results"][model]
    assert cr["recommended_model"] == model
    assert fit["Ea"] == pytest.approx(ea, rel=0.005)
    assert fit["A"] == pytest.approx(a_pre, rel=0.10)


# --------------------------------------------------------------------------- #
# The built-in validation report
# --------------------------------------------------------------------------- #
def test_builtin_validation_report_all_pass():
    report = validation.run_validation()
    failed = [r for r in report.records if not r.passed]
    assert not failed, validation.format_report(report)
    assert set(report.methods) == set(kinetics.METHODS) | {"Coats-Redfern"}
    assert len(report.scenarios) == 5
